// @ts-check
'use strict'

/**
 * Generates the Peggy parser the formula benchmarks measure against, into
 * `.generated/peggy-parser.js`.
 *
 * The grammar is vendored here rather than read out of a sibling project on
 * purpose: it is the reference point for every Peggy number in the README, and
 * a baseline that can change underneath the measurements is not a baseline.
 * It emits the same JSON Logic as `examples/formula.gram`, which the benchmarks
 * assert before timing anything.
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import peggy from 'peggy'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, '..', '..', '.generated', 'peggy-parser.js')

const source = peggy.generate(await readFile(path.join(here, 'grammar.peggy'), 'utf8'), {
  output: 'source',
  format: 'es',
  grammarSource: 'bench/peggy/grammar.peggy',
  allowedStartRules: ['Formula']
})

await mkdir(path.dirname(out), { recursive: true })
await writeFile(out, `// GENERATED by bench/peggy/build.js — do not edit.\n/* eslint-disable */\n\n${source}`)
console.log(`wrote .generated/peggy-parser.js (${(source.length / 1024).toFixed(1)} kB)`)
